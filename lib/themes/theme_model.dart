import 'package:flutter/material.dart';

class TerminalTheme {
  final String name;
  final Color bg;
  final Color surface;
  final Color border;
  final Color prompt;
  final Color textMain;
  final Color red;
  final Color green;
  final Color yellow;
  final Color blue;
  final Color purple;
  final Color dim;

  const TerminalTheme({
    required this.name,
    required this.bg,
    required this.surface,
    required this.border,
    required this.prompt,
    required this.textMain,
    required this.red,
    required this.green,
    required this.yellow,
    required this.blue,
    required this.purple,
    required this.dim,
  });
}
